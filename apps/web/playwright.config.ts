import { defineConfig } from "@playwright/test";

/**
 * Сквозные проверки.
 *
 * Идут против настоящего API и настоящей базы: то, что ломается на стыке —
 * кука сессии, поток прогресса, прокси, — в отдельных тестах слоёв не видно.
 * Поэтому серверы должны быть запущены; тесты их не поднимают, чтобы не
 * трогать рабочие данные без ведома человека.
 */
export default defineConfig({
  testDir: "./e2e",
  timeout: 60_000,
  // В один поток намеренно. Проверки идут против одного процесса API, а
  // рабочий список пересчитывается на каждый запрос: четыре одновременных
  // ответа занимают двадцать шесть секунд вместо трёх. Параллельные потоки
  // мерили бы пропускную способность, а не правильность, и падали бы по
  // сроку в случайном месте — то есть говорили бы «сломано» там, где всё
  // работает. Сама пропускная способность — отдельная задача: площадки надо
  // перевести на счёт прогоном, как уже сделано у тендеров.
  workers: 1,
  use: {
    // По умолчанию — сервер разработки: правку видно сразу, без пересборки.
    // Против собранного интерфейса (nginx на :8080) — `E2E_BASE_URL`. Разница
    // не только в свежести кода: прокси Vite добавляет к ответу в мегабайт
    // ещё пару секунд, и на нём проверки упираются в собственные сроки там,
    // где рабочая сборка отвечает вдвое быстрее.
    baseURL: process.env.E2E_BASE_URL ?? "http://localhost:5173",
    locale: "ru-RU",
    screenshot: "only-on-failure",
  },
  reporter: [["list"]],
});
