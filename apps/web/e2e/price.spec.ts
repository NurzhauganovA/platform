/**
 * Разбор ячейки цены — таблицей входов и итогов.
 *
 * Проверка чистой логики, без браузера: Playwright здесь взят как исполнитель
 * тестов, а не как браузер. Свой набор для модульных проверок означал бы
 * вторую зависимость в образе, который пересобирают по десять раз на дню, —
 * ради двухсот строк разбора это дорого.
 *
 * Считать надо ровно то, что человек имел в виду. Ошибка здесь не падает и не
 * подсвечивается: она молча даёт правдоподобное число — до этой работы
 * «2 * 18000» превращалось в 218000 и уезжало в итог закупки.
 */

import { expect, test } from "@playwright/test";

import { amount, money, parse, total } from "../src/features/cards/money";

test.describe("цена в ячейке", () => {
  test("обычное число остаётся числом", () => {
    const случаи: [string, number][] = [
      ["18000", 18000],
      ["1 250 000", 1250000],
      ["1 250 000 ₸", 1250000],
      ["1250,50", 1250.5],
      ["1250.50", 1250.5],
      ["18 000 тг", 18000],
    ];
    for (const [ввод, итог] of случаи) {
      expect(parse(ввод), ввод).toEqual({ kind: "number", value: итог });
    }
  });

  test("количество на цену считается", () => {
    const случаи: [string, number][] = [
      ["2 * 18000", 36000],
      ["2*18000", 36000],
      ["18000 * 2", 36000],
      ["18 000 * 2", 36000],
      // Русская «х» на той же клавише, что латинская: в русской раскладке
      // она набирается сама собой.
      ["2 х 18000", 36000],
      ["2 x 18000", 36000],
      ["2 × 18000", 36000],
      // Привычка из Excel — просьба посчитать, а не ошибка.
      ["=2*18000", 36000],
      ["3 * 1250,50", 3751.5],
      ["(2 + 1) * 18000", 54000],
      ["36000 / 2", 18000],
      ["18000 + 500", 18500],
      ["18000 - 500", 17500],
    ];
    for (const [ввод, итог] of случаи) {
      expect(parse(ввод), ввод).toEqual({ kind: "formula", value: итог });
    }
  });

  test("невнятица названа невнятицей, а не числом", () => {
    // Каждая из этих строк раньше давала правдоподобное число и уезжала в
    // итог: «2 *» — 2, «по счёту» — ничего, «18000 руб за шт» — 18000.
    for (const ввод of [
      "2 *",
      "* 18000",
      "2 ** 3",
      "по счёту",
      "18000 / 0",
      "()",
      "2 + ",
    ]) {
      expect(parse(ввод).kind, ввод).toBe("broken");
    }
    expect(parse("").kind).toBe("empty");
    expect(parse("   ").kind).toBe("empty");
    expect(amount("2 *")).toBeNull();
  });

  test("ссылок на другие строки нет и не заводим", () => {
    // Таблица живёт копиями: снабжение получает свою, и ссылка, пережившая
    // копирование, указывала бы в чужую таблицу.
    for (const ввод of ["A1", "=A1*2", "СУММ(A1:A5)"]) {
      expect(parse(ввод).kind, ввод).toBe("broken");
    }
  });

  test("итог складывается в копейках, а не в долях", () => {
    // 0.1 + 0.2 в двоичной дроби даёт 0.30000000000000004: на сорока строках
    // итог разъезжается с тем, что человек сложит на калькуляторе.
    expect(total([0.1, 0.2])).toBe(0.3);
    expect(total([18000, 36000, 1250.5])).toBe(55250.5);
    expect(total([])).toBe(0);
  });

  test("сумма показывается разрядами", () => {
    // Разряды отделены неразрывным пробелом — иначе число переносится по
    // строке пополам. Сравниваем по коду знака, а не по виду: обычный и
    // неразрывный пробел на экране неразличимы, и тест на глаз проходил бы
    // при сломанном переносе.
    expect(money(36000)).toBe("36\u00a0000 \u20b8");
    expect(money(1250.5)).toBe("1\u00a0250,50 \u20b8");
    expect(money(900)).toBe("900 \u20b8");
  });
});
