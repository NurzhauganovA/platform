/**
 * Что можно этому человеку — в браузере.
 *
 * Права приходят в ответе о себе (`/api/auth/me`) и кэшируются запросом: они
 * считаются при разборе сессии, то есть меняются только со следующим входом, и
 * спрашивать их чаще незачем.
 *
 * Нужны, чтобы не рисовать того, что ответит отказом. Кнопка, которая на
 * нажатие отвечает «недостаточно прав», читается как поломка — а человек к
 * этому моменту уже уверен, что сделал дело. Столбец с себестоимостью, который
 * виден, но пуст, читается так же.
 *
 * **Это удобство, а не защита.** Проверка живёт на эндпоинте; спрятать кнопку
 * и оставить эндпоинт открытым — самый распространённый способ отдать
 * себестоимость наружу. Поэтому здесь нельзя «просто скрыть» то, что сервер не
 * закрывает: сначала право на эндпоинте, потом уже показ.
 */

import { useQuery } from "@tanstack/react-query";
import { auth } from "@/api/tender";

export function usePermissions(): Set<string> {
  const { data } = useQuery({
    queryKey: ["me"],
    queryFn: auth.me,
    staleTime: 5 * 60_000,
  });
  return new Set(data?.permissions ?? []);
}

/**
 * Можно ли. Администратор проходит везде — он и так распоряжается доступами.
 *
 * Пока права не приехали, отвечает «нельзя»: показать кнопку и отобрать её
 * через полсекунды хуже, чем показать на полсекунды позже.
 */
export function useCan(): (permission: string) => boolean {
  const permissions = usePermissions();
  return (permission: string) =>
    permissions.has("admin") || permissions.has(permission);
}
