/**
 * Данные закупки в карточке — та же панель, что в «Лотах портала».
 *
 * Именно та же, а не похожая: `DetailPanel` берётся как есть. Своя копия уже
 * была написана и оказалась ошибкой — она повторяла разделы по-своему, и
 * человек, привыкший к списку, в карточке искал знакомое и не находил. А со
 * временем копия разошлась бы и по существу: в списке у лота одна сумма, в
 * карточке другая.
 *
 * Открывается из шапки лота, а не из правого столбца. В столбце это был
 * отдельный блок с заголовком и кнопкой — три строки высоты ради одного
 * нажатия, которое делают раз за работу с лотом. В шапке рядом с номером
 * закупки — это то же место, где человек читает, что за лот перед ним.
 *
 * Панель идёт в режиме сведений: сроки, способ закупки, что покупают — и всё.
 * Спецификация, документы и обсуждение у карточки свои, и повторённые здесь
 * они вели в другую сторону: человек заводил обсуждение из карточки лота,
 * который уже взят, и получал вторую дверь туда, куда есть первая.
 */

import { useState } from "react";
import { useQuery } from "@tanstack/react-query";
import type { Card } from "@/api/cards";
import { DetailPanel } from "@/features/worklist/DetailPanel";
import { worklists, type WorklistSlug } from "@/api/worklist";

export function LotFacts({ card }: { card: Card }) {
  const [open, setOpen] = useState(false);

  return (
    <>
      <button
        type="button"
        onClick={() => setOpen(true)}
        title="Сроки, способ закупки и что покупают — как на площадке сейчас"
        className="shrink-0 rounded-[8px] border border-baseline px-2.5 py-1 text-xs text-ink transition hover:bg-plane"
      >
        Данные закупки
      </button>

      {open && (
        <DetailPanel
          slug={card.module as WorklistSlug}
          id={card.row_id}
          // Только сведения. Спецификация лежит во вкладке «Разбор», документы
          // — во вкладке «Файлы», соседние лоты и обсуждение открываются из
          // «Лотов портала»: здесь они повторяли бы карточку саму себе.
          facts
          // Отметка «в работе» стоит всегда: карточка и есть результат
          // взятия, и кнопка «Взять в работу» в ней предлагала бы завести
          // вторую по тому же лоту. Этап здесь `analysis` — у отметки свой
          // короткий набор этапов, и состояние карточки в него не ложится:
          // их четырнадцать, а тут три.
          work={{ id: card.id, code: card.code, stage: "analysis" }}
          onClose={() => setOpen(false)}
          onOpen={() => undefined}
        />
      )}
    </>
  );
}

/**
 * Ссылка на закупку у площадки.
 *
 * Адрес снимает выгрузка и хранит рядом с лотом — в карточке его нет, и взять
 * неоткуда, кроме разбора. Запрос тот же, что у «Требований заказчика» под
 * полем замечания: ключ совпадает, и второй раз по сети никто не идёт.
 *
 * Ссылки нет — нет и кнопки. Мёртвая ссылка хуже отсутствующей: человек
 * нажимает, попадает на пустую страницу портала и решает, что закупку сняли.
 */
export function PortalLink({ card }: { card: Card }) {
  const { data } = useQuery({
    // Сведениями, а не разбором целиком: отсюда нужен один адрес, а полный
    // разбор идёт за соседними лотами на портал и отвечает до минуты — ради
    // ссылки, которая лежит в той же строке базы.
    queryKey: [card.module, "item", card.row_id, "facts"],
    queryFn: () =>
      worklists.detail(card.module as WorklistSlug, card.row_id, "", true),
    retry: false,
    staleTime: 60_000,
  });

  if (!data?.url) return null;

  return (
    <a
      href={data.url}
      target="_blank"
      rel="noreferrer"
      title="Карточка закупки на площадке"
      className="shrink-0 rounded-[8px] border border-baseline px-2.5 py-1 text-xs text-ink transition hover:bg-plane"
    >
      На площадке ↗
    </a>
  );
}
