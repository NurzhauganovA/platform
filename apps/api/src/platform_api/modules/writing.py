"""Написание замечания к технической спецификации.

Замечание пишет модель, но решает не она. Ссылки на нормы подставляются из
списка оснований модуля (`grounds.py`), а не сочиняются: выдуманный «пункт 415
Правил» выглядит убедительно, и ошибку видит только заказчик, который на этом
основании замечание и отклонит.

Стиль задан здесь, а не просьбой в подсказке. Просьба «пиши без тире»
выполняется через раз, а текст уходит заказчику официальным обращением: список
с дефисами в нём читается как черновик. Поэтому модель просят, а потом
проверяют — и правит текст код.

Что именно убирается: тире и дефис в роли знака препинания, значки списков,
отступы в начале строк и двоеточия. Дефис внутри слова остаётся: «из-за» и
«Санкт-Петербург» пишутся через него, и вычищать его значит портить слова
ради вида.

Длина ограничена намеренно. Замечание читает специалист заказчика, у которого
таких десяток за день; на трёх страницах требование теряется, и отвечают
отпиской по последнему абзацу.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import date
from decimal import Decimal

from platform_api.modules.goszakup.grounds import GROUNDS, PRINCIPLES, REQUESTS, brand_threshold

MAX_LENGTH = 6_000
"""Предел длины замечания.

Шесть тысяч знаков — это примерно две страницы, столько же было в принятых
замечаниях. Обрезка идёт по границе абзаца: оборванная на полуслове ссылка на
норму хуже отсутствующей.
"""

MIN_LENGTH = 200
"""Ниже этого замечание считается несостоявшимся.

Модель, которой нечего сказать, отвечает вежливым абзацем ни о чём. Отдать его
менеджеру как готовое значит потратить его время на чтение пустоты — лучше
честно показать, что замечание не написалось.
"""


@dataclass(frozen=True, slots=True)
class Subject:
    """Закупка, к которой пишется замечание."""

    code: str
    """Код строки в платформе — «GZ000001»."""

    purchase_number: str
    title: str
    customer: str
    amount: Decimal | None
    count: Decimal | None
    unit: str
    enstru_code: str
    enstru_name: str
    lot_number: str = ""
    spec_text: str = ""
    """Текст технической спецификации. Ради него всё и затевается: требования
    под одного поставщика лежат в файле, а не в названии лота."""


@dataclass(frozen=True, slots=True)
class Draft:
    """Написанное замечание."""

    text: str
    grounds: tuple[str, ...]
    """Основания, которые модель сочла применимыми. Показываются менеджеру
    рядом с текстом: по ним видно, о чём замечание, не читая его целиком."""

    trouble: str = ""
    """Почему не написалось. Пусто, если написалось."""

    model: str = ""
    """Какая модель ответила на самом деле.

    Не та, что стоит в настройках: у основной кончается квота посреди дня, и
    дописывает запасная. Через полгода при разборе отказа нужно знать, чем
    замечание написано, а не чем его собирались писать.
    """


def prompt(subject: Subject, *, today: date) -> str:
    """Подсказка модели.

    Собирается из закупки и списка оснований. Спецификация идёт последней и
    целиком: именно её модель и разбирает, а всё, что выше, — рамка.
    """
    порог = brand_threshold(today)
    правила = [
        "Ты пишешь замечание к технической спецификации государственной закупки "
        "от имени поставщика компьютерной техники.",
        "Цель замечания снять из спецификации требования, которые сужают круг "
        "участников до одного поставщика и не дают предложить равноценное оборудование.",
        "",
        "Как писать.",
        "Пиши деловым языком, короткими предложениями, по существу.",
        "Каждое замечание начинай с того, что написано в спецификации, "
        "потом почему это нарушение, потом ссылку на норму.",
        "Ссылки на нормы бери только из списка оснований ниже. "
        "Другие пункты и статьи не приводи, даже если помнишь их.",
        "Не используй тире, двоеточия, дефисы как знак препинания, "
        "значки списков и отступы в начале строк.",
        "Не нумеруй абзацы. Каждое замечание отдельным абзацем.",
        "Не приводи выдуманные номера отменённых закупок и не ссылайся на прецеденты.",
        "Не пиши вступление и не пиши подпись. Только сами замечания.",
        f"Уложись в {MAX_LENGTH // 6} слов.",
        "",
        "Если в спецификации нарушений нет, ответь одним словом НЕТ.",
        "",
        "Закупка.",
        f"Номер {subject.purchase_number}.",
    ]
    # Пустые сведения пропускаются, а не подставляются пустой строкой: «Заказчик
    # .» в подсказке модель принимает за настоящее имя и переписывает в текст.
    for line in (
        f"Лот {subject.lot_number}." if subject.lot_number else "",
        f"Предмет {subject.title}." if subject.title else "",
        f"Код ЕНС ТРУ {subject.enstru_code} {subject.enstru_name}.".strip(),
        f"Заказчик {subject.customer}." if subject.customer else "",
        _amount_line(subject, порог),
    ):
        if line.strip():
            правила.append(line)

    правила += ["", "Основания. Приводить можно только эти нормы."]
    for ground in GROUNDS:
        правила.append(f"{ground.title}. Искать {ground.look_for}. Норма {ground.law}.")
    правила += [
        "",
        # Один раз в конце, а не в каждом абзаце. Без этого уточнения модель
        # приписывает общую ссылку к каждому нарушению: замечание из четырёх
        # абзацев вырастает вдвое, а читается как заполненный бланк, и
        # специалист заказчика доходит до сути с четвёртого раза.
        f"В самом конце, одним предложением и только один раз, сошлись на {PRINCIPLES}.",
        "Ни в одном другом абзаце эту общую ссылку не повторяй.",
        "После неё напиши, что просим " + " и ".join(REQUESTS) + ".",
        "",
        "Техническая спецификация заказчика.",
        subject.spec_text.strip() or "(файл не приложен, разбирай по предмету закупки)",
    ]
    return "\n".join(правила).strip()


def _amount_line(subject: Subject, порог: Decimal | None) -> str:
    """Строка про сумму и порог тысячекратного МРП.

    Порог приводится только когда он известен и когда сумма его превышает.
    Иначе довод «сумма превышает» становится неверным — а на нём держится
    половина замечания о бренде.
    """
    if subject.amount is None:
        return ""
    штук = f" в количестве {_plain(subject.count)} {subject.unit}".rstrip() if subject.count else ""
    строка = f"Сумма {_plain(subject.amount)} тенге{штук}."
    if порог is not None and subject.amount > порог:
        строка += (
            f" Сумма превышает тысячекратный размер месячного расчётного показателя "
            f"{_plain(порог)} тенге, поэтому указывать конкретный бренд в этой закупке нельзя."
        )
    return строка


def shape(raw: str) -> Draft:
    """Приводит ответ модели к тому виду, в каком его отправляют.

    Отказ модели («НЕТ») превращается не в пустой текст, а в объяснённую
    неудачу: пустое поле в интерфейсе выглядит поломкой платформы, а не
    решением «здесь придраться не к чему».
    """
    text = _clean(raw)
    if not text or text.upper().startswith("НЕТ"):
        return Draft(text="", grounds=(), trouble="Модель не нашла в спецификации нарушений")
    if len(text) < MIN_LENGTH:
        return Draft(
            text="",
            grounds=(),
            trouble="Модель ответила слишком коротко, чтобы это было замечанием",
        )
    return Draft(text=_trim(text), grounds=_grounds_in(text))


# Значок списка в начале строки: дефис, тире, звёздочка, точка, «1)» и «1.».
_BULLET = re.compile(r"^[\s ]*(?:[-–—•*·]+|\d+[.)])[\s ]+", re.M)

# Тире как знак препинания: с пробелом хотя бы с одной стороны. Дефис внутри
# слова («из-за», «Санкт-Петербург») под это не попадает и остаётся.
_DASH = re.compile(r"[\s ]+[-–—][\s ]+|^[\s ]*[-–—][\s ]+", re.M)

_INDENT = re.compile(r"^[ \t ]+", re.M)
_BLANKS = re.compile(r"\n{3,}")
_SPACES = re.compile(r"[ \t ]{2,}")

# Двоеточие убирается вместе с лишним пробелом за ним, а не заменяется на
# точку: «указано: Моноблок HP» с точкой распадается на два огрызка.
_COLON = re.compile(r"[\s ]*:[\s ]*")


def _clean(raw: str) -> str:
    text = (raw or "").replace("\r\n", "\n").replace("\r", "\n")
    # Разметку модель добавляет по привычке, даже когда её не просили.
    text = text.replace("**", "").replace("##", "").replace("`", "")
    text = _BULLET.sub("", text)
    text = _DASH.sub(" ", text)
    text = _COLON.sub(" ", text)
    text = _INDENT.sub("", text)
    text = _SPACES.sub(" ", text)
    text = _BLANKS.sub("\n\n", text)
    return "\n".join(line.rstrip() for line in text.split("\n")).strip()


def _trim(text: str) -> str:
    """Обрезает по границе абзаца, а не по знаку.

    Оборванная на полуслове ссылка на норму хуже отсутствующей: заказчик
    отвечает, что такого пункта нет.
    """
    if len(text) <= MAX_LENGTH:
        return text
    kept: list[str] = []
    length = 0
    for paragraph in text.split("\n\n"):
        if length + len(paragraph) > MAX_LENGTH:
            break
        kept.append(paragraph)
        length += len(paragraph) + 2
    return "\n\n".join(kept) if kept else text[:MAX_LENGTH]


def _grounds_in(text: str) -> tuple[str, ...]:
    """Какие основания модель привела на самом деле.

    По словам самого замечания, а не по тому, что модель о себе заявила:
    заявленное и приведённое расходятся, а менеджеру в списке нужно второе.

    Признаки берутся из `marks` основания и никогда из номера нормы. Номера
    повторяются: «пункт 3 статьи 6» стоит и у программного обеспечения, и у
    сборного лота, а «412» встречается внутри кода ЕНС ТРУ. Поиск по числу
    отмечал применёнными все шесть оснований разом.
    """
    lowered = text.lower()
    return tuple(ground.key for ground in GROUNDS if any(mark in lowered for mark in ground.marks))


def _plain(value: Decimal) -> str:
    """Число словами человека: без хвоста нулей и с пробелом на разряд.

    Пробел обычный, а не неразрывный. Неразрывный не даёт числу разорваться
    при переносе, но здесь оно уходит в подсказку модели и в обычный текст —
    а невидимое отличие в подсказке стоит получаса отладки, когда сравнение
    строк не сходится непонятно почему.
    """
    quantized = value.normalize()
    whole = f"{quantized:,.2f}".rstrip("0").rstrip(".")
    return whole.replace(",", " ")
