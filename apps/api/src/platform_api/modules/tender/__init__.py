"""Тендерный модуль платформы.

Тонкий слой над пакетом `tender-analyze`: разбор документов, сравнение
предложений, поиск на рынках и сборка нашего КП живут там и остаются
доступными из его CLI. Здесь — только перевод этого на язык HTTP.

Правило простое: в этом каталоге не должно появиться ни одной строки
предметной логики. Как только сюда переедет расчёт цены или разбор документа,
одно и то же начнёт считаться двумя способами — в вебе и в CLI, — и они
разойдутся ровно на той закупке, где ошибка стоит дороже всего.
"""

from __future__ import annotations

from platform_api.modules import ModuleSpec, NavItem
from platform_api.modules.tender import health
from platform_api.modules.tender.jobs import jobs
from platform_api.modules.tender.router import router

module = ModuleSpec(
    slug="tender",
    title="Тендеры",
    description="Разбор тендерной документации, сравнение КП и наши предложения",
    router=router,
    # Один пункт — отбор. Заведение закупки папкой из меню убрано: разбор всё
    # равно идёт у тендерщика на машине, где эти папки лежат, а платформа
    # показывает то, что он уже разобрал. Эндпоинты загрузки остались рабочими
    # (`/tender/cases`), пункт вернётся, когда папки поедут через платформу.
    #
    # «История цен» и «Конкуренты» в ядре есть (`PriceHistoryService`,
    # `CompetitorAnalyzer`), но страниц под них пока нет — а пункт меню,
    # который молча уводит на чужой раздел, хуже отсутствующего: человек
    # решает, что сломался вход, и перестаёт верить остальным пунктам тоже.
    nav=(
        # Отбор и аналитика — работа отдела разбора. Снабжению там нечего
        # делать: суммы и маржа ему не показываются, а без них отбор пуст.
        # «В работе» видят оба — это их общий стол.
        NavItem(
            title="Отбор закупок",
            path="/tender/worklist",
            icon="target",
            roles=("admin", "analyst"),
        ),
        NavItem(title="В работе", path="/tender/works", icon="briefcase"),
        NavItem(
            title="Аналитика",
            path="/tender/analytics",
            icon="chart",
            roles=("admin", "analyst"),
        ),
    ),
    jobs=jobs,
    health=health.check,
)

__all__ = ["module"]
