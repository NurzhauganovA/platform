"""Техническое задание позиции — то единственное, что видит снабжение.

Снабжению нужен предмет закупки и требования к нему. Исходный документ
заказчика ему открывать нельзя: в ТЗ стоят цены ценового заключения, реквизиты
сторон и печати, а от цены заказчика считается наша — увидев её, снабженец
знает потолок, по которому с ним же и будут торговаться поставщики.

Поэтому задание не вычищается, а **собирается заново** — из того, что ядро уже
разобрало, и только из перечисленных здесь полей. Разница принципиальная:
вычистка отвечает «мы убрали всё, что вспомнили», сборка — «сюда попало только
то, что названо». Первая ошибается молча и ровно один раз.

Платного шага здесь нет. Всё, из чего собирается задание, ядро извлекло при
разборе документов, и лежит это в его базе: открытая страница не тратит денег.

Черновик записывается в саму работу при взятии её в работу, а не считается на
каждый показ. Отбор пересобирается при каждом прогоне, названия у позиций
меняются — а задание, отданное снабжению, меняться от этого не должно.
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from dataclasses import dataclass
from decimal import Decimal
from typing import Any

MAX_LENGTH = 40_000
"""Предел длины задания.

Половина технических заданий укладывается в две тысячи знаков, девять из
десяти — в тринадцать тысяч. Сорок тысяч закрывают почти всё; у остатка хвост
отрезается с прямой пометкой об этом. Молча обрезанное задание хуже длинного:
снабжение не знает, что читает половину.
"""


@dataclass(frozen=True, slots=True)
class Position:
    """Позиция глазами заказчика. Денежных полей здесь нет намеренно."""

    name: str
    specification: str
    quantity: Decimal | None
    unit: str
    ens_code: str

    source: str = ""
    """Документ заказчика, из которого позиция взята.

    В папке лежат пять служебных записок на пять разных нужд, и требования у
    каждой свои. Один общий документ на всех означает задание на кабель, в
    котором описан индукционный котёл."""


@dataclass(frozen=True, slots=True)
class Source:
    """Документ заказчика, из которого берётся задание.

    Хранится текстом, а не ссылкой на файл: исходный документ снабжению
    закрыт, а текст его технической части — ровно то, что ему нужно.
    """

    name: str
    kind: str
    body: str


@dataclass(frozen=True, slots=True)
class CaseSpec:
    """Требования закупки — белый список полей, годных для снабжения.

    Собирается попутно со строками отбора: закупка в этот момент уже построена,
    и отдельного обращения к базе ядра это не стоит.
    """

    subject: str
    requirements: tuple[str, ...]
    delivery: str
    warranty: str
    positions: tuple[Position, ...]
    source: str
    """Из какого документа собрано. Спорное требование нужно уметь проверить —
    разбору исходный документ по-прежнему открыт."""

    bodies: tuple[Source, ...] = ()
    """Технические части всех документов заказчика в папке.

    По одной на документ, а не одна на закупку: позиция берёт текст своего.
    Какого именно — знает ядро, оно проставляет имя при сборке закупки."""

    body: str = ""
    """Техническая часть документа заказчика — его собственный текст.

    Пересказ модели годился бы, если бы речь шла о понимании. Но снабжение по
    этому тексту закупает: марка стали, допуск, класс защиты и номер ГОСТа
    должны стоять теми же словами, что и у заказчика. Выжимка в три строки
    теряет как раз таблицу с размерами.
    """


def gather(case: Any) -> CaseSpec:
    """Требования закупки из разобранных документов.

    Требования берутся из ТЗ и МЗ — документов заказчика. Из коммерческих
    предложений их брать нельзя: там поставщик пишет, что удобно ему.
    """
    customer = [
        document.insight
        for document in case.documents
        if document.insight is not None and str(document.insight.kind) in _CUSTOMER_KINDS
    ]
    from_file = next(
        (
            document.source.name
            for document in case.documents
            if document.insight is not None and str(document.insight.kind) == "ТЗ"
        ),
        "",
    )
    docs = _customer_documents(case)
    doc = docs[0] if docs else Source(name="", kind="", body="")
    return CaseSpec(
        subject=limited(_line(case.subject)),
        requirements=tuple(
            cleaned for item in _requirements(customer, case) if (cleaned := limited(item))
        ),
        # Место поставки снабжению не нужно: оно ищет товар и цену, а везут
        # после подписания договора. От вычистки эта строка обычно и не
        # остаётся — в ней один адрес.
        delivery=limited(_first(insight.delivery_terms for insight in customer)),
        warranty=limited(_first(insight.warranty for insight in customer)),
        positions=tuple(
            Position(
                name=_line(item.name),
                specification=_line(item.specification),
                quantity=item.quantity,
                unit=_line(item.unit),
                ens_code=_line(item.ens_code),
                source=_line(getattr(item, "source_document", "")),
            )
            for item in case.requested
        ),
        source=doc.name or from_file,
        body=doc.body,
        bodies=docs,
    )


_CUSTOMER_KINDS = frozenset({"ТЗ", "МЗ"})
"""Чьи требования считаем требованиями закупки. Документы поставщиков сюда не
входят: в КП написано то, что удобно приславшему."""


def draft(folder_path: str, title: str) -> tuple[str, str]:
    """Черновик задания по позиции: сам текст и имя документа-источника.

    Пусто, если закупку ещё не разбирали. Пустое задание честнее выдуманного:
    снабжение по нему поймёт, что задание нужно написать руками, а не что
    требований к товару нет.
    """
    from platform_api.modules.tender import worklist

    known = worklist.case_spec(folder_path)
    if known is None:
        return "", ""
    return render(known, title), source_of(known, title)


def render(spec: CaseSpec, title: str) -> str:
    """Задание по позиции — текстом, каким его и увидят.

    Текстом, а не набором полей: задание правит человек из разбора перед
    передачей, и «дописать строчку» должно оставаться дописыванием строчки.
    Разложенное по восьми полям задание правят так же часто, как заполняют
    восемь полей, то есть никогда.
    """
    matched = _match(spec.positions, title)
    items = (matched,) if matched is not None else spec.positions
    if not items:
        # Позиций заказчика ядро не нашло — папка без ценового заключения.
        # Название строки здесь единственное, что известно о товаре, и без
        # него задание выходит без предмета вовсе.
        items = (
            Position(name=_line(title), specification="", quantity=None, unit="", ens_code=""),
        )

    # Предмет закупки не печатается: он называет закупку целиком, а с ней —
    # месторождение и заказчика («Реконструкция склада рудника Инкай»).
    # Названия месторождений списком не закрыть, а позиция и так названа
    # строкой ниже, своим именем.
    parts: list[str] = ["ТЕХНИЧЕСКОЕ ЗАДАНИЕ", ""]

    for index, position in enumerate(items, start=1):
        number = f"{index}. " if len(items) > 1 else ""
        parts.append(f"{number}{position.name or _line(title)}")
        if position.quantity is not None:
            parts.append(f"   Количество: {_amount(position.quantity)} {position.unit}".rstrip())
        if position.ens_code:
            parts.append(f"   Код ЕНС ТРУ: {position.ens_code}")
        if position.specification:
            parts.append(f"   Характеристики: {position.specification}")
        parts.append("")

    body = _about(spec, matched, _body_for(spec, matched))
    if body:
        # Текст самого документа заказчика. Пересказ здесь не годится: марка
        # стали, допуск и номер ГОСТа должны стоять теми же словами, иначе
        # снабжение купит похожее.
        parts += ["ТЕХНИЧЕСКИЕ ТРЕБОВАНИЯ", "", body]
    else:
        # Документ не прочитался — собираем из того, что ядро из него поняло.
        if spec.requirements:
            parts.append("ТРЕБОВАНИЯ ЗАКАЗЧИКА")
            parts += [f"— {item}" for item in spec.requirements]
            parts.append("")
        if spec.delivery:
            parts += ["МЕСТО И УСЛОВИЯ ПОСТАВКИ", spec.delivery, ""]
        if spec.warranty:
            parts += ["ГАРАНТИЯ", spec.warranty, ""]

    assembled = limited("\n".join(parts)).strip()
    if len(assembled) <= MAX_LENGTH:
        return assembled
    # Обрезанное молча задание хуже длинного: снабжение не узнает, что читает
    # половину, и закупит по половине.
    return assembled[:MAX_LENGTH] + "\n\n[…] Документ длиннее — запросите остаток у отдела разбора"


_ORGANIZATION = re.compile(
    r"(?:ТОО|АО|АҚ|ЖШС|ГКП|РГП|НАК|ЧУ|ГУ|КГП)\s*[«\"][^»\"]{1,80}[»\"]", re.IGNORECASE
)
"""Название организации в кавычках после её вида.

Заменяется, а не выбрасывается вместе со строкой: организация упоминается
посреди требования, и вычеркнутое предложение унесло бы с собой требование.
"""

_PERSON = re.compile(r"[А-ЯЁӘҚҢҒҮҰҺІ][а-яёәқңғүұhі]+\s+[А-ЯЁӘҚҢҒҮҰҺІ]\.\s?[А-ЯЁӘҚҢҒҮҰҺІ]\.")
_CONTACT = re.compile(
    r"[\w.+-]+@[\w-]+\.[\w.]+|\+?7[\s(-]*\d{3}[)\s-]*\d{2,3}[\s-]*\d{2}[\s-]*\d{2}"
)
_LOT_NUMBER = re.compile(r"(?:лот|объявлени\w*|закупк\w*|тендер\w*)\s*№\s*[\w-]+", re.IGNORECASE)

_WHO_AND_WHERE = re.compile(
    r"место\s+поставки|адрес\s+поставки|адрес\s+доставки|грузополучател|пункт\s+назначения|"
    r"\bзаказчик|\bпокупател|\bгрузоотправител|конечный\s+потребитель|"
    r"[А-ЯЁ][а-яё]+ская\s+област|\bрайон\b|\bмкр\b|микрорайон|\bул\.|\bулица\b|"
    r"\bг\.\s?[А-ЯЁӘҚ]|\bпос\.|\bпос[её]лок\b|\bсел[оа]\b|\bаул\b|рудник\w*|кеніш|"
    r"промплощадк|\bиндекс\b|утверждаю|согласовано|"
    r"\bдиректор|\bначальник|\bзаместител|главный\s+инженер|\bисп\.|"
    r"серіктест|кәсіпорн|товарищество\s+с\s+огранич|акционерное\s+общество|"
    r"совместное\s+предприятие|"
    r"\bфилиал\w*|месторождени|"
    # Заголовок документа и период закупки: «Техническое задание … на 2026 год».
    # Требованием такая строка не бывает, а название месторождения в ней стоит
    # регулярно — и месторождений столько, что списком их не закрыть.
    r"тех\.?\s*задание|техническое\s+задание|на\s+20\d\d\s+год",
    re.IGNORECASE,
)
"""Кто заказчик и куда везти.

Снабжение пересылает задание поставщику. Узнав заказчика и рудник, поставщик
находит закупку в реестре, видит цену заключения — и либо поднимает свою до
неё, либо идёт на торги сам. Это не осторожность вообще, а единственное, чем
мы отличаемся от него в этой сделке: он умеет купить у завода не хуже нас.

Место поставки снабжению и не нужно: оно ищет товар и цену, а везти будут
после подписания договора.
"""


_COMPANY_LEFT = re.compile(r"\b(?:ТОО|АҚ|ЖШС|ГКП|РГП|НАК|ЧУ|КГП)\b", re.IGNORECASE)
"""Вид организации, оставшийся в строке после замены названия.

Правильно записанное «ТОО «Х»» заменяется целиком раньше и сюда не доходит.
Доходит то, у чего распознавание потеряло закрывающую кавычку, — в сканах это
обычное дело: «ТОО «ДП «ОРТ АЛЬIК)>». Где кончается название, непонятно, и
подставить вместо него нечего, поэтому строка выбрасывается целиком.

Требованием к товару такая строка почти не бывает: вид организации в
техническом задании стоит там, где говорят о заказчике.
"""

_PLACES = re.compile(
    r"\b(?:Астан[аеуы]|Алмат[ыинскогй]+|Шымкент\w*|Караганд\w+|Актобе|Тараз\w*|"
    r"Павлодар\w*|Усть-Каменогорск\w*|Семе[йя]|Атырау\w*|Костана[йи]\w*|"
    r"Кызылорд\w+|Уральск\w*|Петропавловск\w*|Актау|Темиртау|Туркестан\w*|"
    r"Кокшетау|Талдыкорган\w*|Экибастуз\w*|Рудны[йм]|Жезказган\w*|Байкон[уы]р\w*|"
    r"Балхаш\w*|Сатпаев\w*|Степногорск\w*|Кентау|Аксу|Жанаозен\w*|"
    r"Акмолинск\w+|Актюбинск\w+|Атырауск\w+|Восточно-Казахстанск\w+|Жамбылск\w+|"
    r"Западно-Казахстанск\w+|Карагандинск\w+|Костанайск\w+|Кызылординск\w+|"
    r"Мангистауск\w+|Павлодарск\w+|Северо-Казахстанск\w+|Туркестанск\w+|"
    r"Улытауск\w+|Абайск\w+|Жетысуск\w+)\b",
    re.IGNORECASE,
)
"""Города и области Казахстана.

Список закрытый — в отличие от названий организаций, которых бесконечно много.
Место поставки в документе стоит и без слова «поставка»: отдельной строкой
«Шымкент 2026» под подписью, в шапке, в колонке таблицы. По нему поставщик
находит закупку не хуже, чем по имени заказчика.
"""


def limited(text: str, also: Sequence[str] = ()) -> str:
    """Задание без заказчика, адресов, контактов и подписантов.

    Обезличивание идёт двумя способами. Название организации и фамилия
    заменяются на месте: они стоят посреди требования, и вычеркнутая строка
    унесла бы требование с собой. Строки про место поставки и утверждающих
    выбрасываются целиком — в них ничего, кроме этого, и нет.

    «Область» здесь опознаётся только в виде «Туркестанская область»:
    «область применения» и «область измерений» — заголовки технического
    задания, и потерять их значит отдать снабжению документ без начала.

    `also` — имена, известные по самой работе: заказчик этого лота записан у
    нас, и вычистить его можно прицельно, не гадая по написанию. Общие правила
    закрывают то, чего мы заранее не знаем; это — то, что знаем точно.
    """
    by_name = _by_name(also)
    lines: list[str] = []
    for raw in text.splitlines():
        row_text = by_name.sub("[организация]", raw) if by_name else raw
        row_text = _ORGANIZATION.sub("[организация]", row_text)
        row_text = _PERSON.sub("[Ф.И.О.]", row_text)
        row_text = _LOT_NUMBER.sub("[номер закупки]", row_text)
        row_text = " ".join(_CONTACT.sub("", row_text).split())
        if (
            _WHO_AND_WHERE.search(row_text)
            or _COMPANY_LEFT.search(row_text)
            or _PLACES.search(row_text)
        ):
            continue
        if row_text or (lines and lines[-1]):
            lines.append(row_text)
    return "\n".join(lines).strip()


def document(heading: str, sections: Sequence[tuple[str, str]]) -> bytes:
    """Задание файлом .docx — тем, что снабжение перешлёт поставщику.

    Разделами, а не одним текстом: по лоту из шести позиций поставщику
    отправляют один файл, а не шесть писем. Тот же вызов с одним разделом даёт
    задание по отдельной позиции.

    Пересылать вместо файла ссылку на платформу нельзя: за той же позицией там
    стоит себестоимость, и «просто не открывайте соседнюю вкладку» отделом
    снабжения не обеспечивается.
    """
    from io import BytesIO

    from docx import Document
    from docx.shared import Pt

    file = Document()
    normal = file.styles["Normal"]
    normal.font.name = "Calibri"
    normal.font.size = Pt(11)

    header = file.add_paragraph()
    run = header.add_run(heading)
    run.bold = True
    run.font.size = Pt(13)

    for subheading, body in sections:
        if subheading:
            paragraph = file.add_paragraph()
            row_text = paragraph.add_run(subheading)
            row_text.bold = True
            row_text.font.size = Pt(12)
        for content in body.splitlines():
            paragraph = file.add_paragraph(content)
            # Заголовки разделов набраны прописными — по ним и отбиваются,
            # чтобы не заводить вторую разметку рядом с той, которую правит
            # человек.
            if content and content == content.upper() and any(label.isalpha() for label in content):
                paragraph.runs[0].bold = True
        file.add_paragraph("")

    stream = BytesIO()
    file.save(stream)
    return stream.getvalue()


