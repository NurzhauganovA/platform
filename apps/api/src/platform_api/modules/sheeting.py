"""Подсказка модели и разбор ответа для таблицы спецификации.

Отделено от похода в модель (`sheeter.py`) по той же причине, что и у
замечания: подсказку и очистку ответа проверяют тестами без сети и без денег,
а наружу остаётся один вызов, который в тестах подменяется.

Задача модели узкая и потому выполнимая: **разложить**, а не пересказать.
Спецификация приходит сплошным текстом на три тысячи знаков, где требования к
процессору, памяти и монитору идут подряд через маркеры списка. Человек
раскладывает это в таблицу руками за двадцать минут на лот, и делает это
каждый раз заново.

Три столбца, и у каждого своя строгость:

- **Предмет** — короткое слово склада: «проц», «озу», «ссд». По нему снабжение
  ищет товар, и длинное «Центральный процессор (CPU)» тут только мешает.
- **Требование заказчика** — дословно из спецификации. Это то, чем меряется
  соответствие заявки, и пересказ здесь означает поданную заявку по
  придуманным требованиям. Модели прямо запрещено сокращать, обобщать и
  дополнять.
- **Кратко** — выжимка для того, кто подбирает модель: числа столбиком, три
  строки от силы. Пересказ требования здесь не нужен — оно рядом, дословное.

Строк должно быть ровно столько, сколько предметов в спецификации. Пропущенный
блок питания — это заявка без блока питания.

Составной предмет при этом идёт узлами, а не одной строкой. Моноблок закупают
целиком, но подбирают по частям: у экрана своя диагональ, у процессора свои
ядра, и снабжение ищет их порознь. Делить или нет, решает модель по самой
спецификации — у процессора узлов нет, и разносить его частоту с кэшем по
строкам нельзя.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass

from platform_api.logging import get_logger

logger = get_logger(__name__)

MAX_SPEC = 60_000
"""Сколько знаков спецификации отдавать модели.

Шестьдесят тысяч — это примерно тридцать страниц, вдвое больше самой длинной
спецификации, что нам встречалась. Предел стоит не ради экономии, а чтобы
случайно приложенный к закупке многотомник не съел окно модели целиком: она
тогда отвечает обрывком, и обрыв приходится на конец таблицы — там, где
кабели и мелочь, которую в заявке как раз и забывают.
"""


@dataclass(frozen=True, slots=True)
class Row:
    """Одна строка таблицы: предмет, требование, выжимка."""

    subject: str
    demand: str
    brief: str


@dataclass(frozen=True, slots=True)
class Sheet:
    """Что вернула модель."""

    rows: tuple[Row, ...] = ()
    trouble: str = ""
    """Почему не получилось — словами для человека, а не кодом ошибки."""


def prompt(*, title: str, spec: str) -> str:
    """Собирает подсказку по тексту спецификации.

    Название лота идёт рядом со спецификацией: по нему модель понимает, что
    перед ней — системный блок в сборе или один монитор, и не заводит строки
    на то, чего в закупке нет.
    """
    body = spec.strip()[:MAX_SPEC]
    return _PROMPT.format(title=title.strip() or "не указано", spec=body)


def shape(raw: str) -> Sheet:
    """Достаёт таблицу из ответа модели.

    Ответ приходит JSON-массивом, но модель любит обернуть его в ```json —
    поэтому сначала снимаем обёртку, а не разбираем как есть. Разбор упал —
    это не поломка платформы: таблица остаётся несобранной, человек видит
    причину и раскладывает спецификацию руками.
    """
    text = _unwrap(raw)
    if not text:
        return Sheet(trouble="Модель вернула пустой ответ")

    try:
        payload = json.loads(text)
    except ValueError as exc:
        logger.warning("sheeting.not_json", error=str(exc))
        return Sheet(trouble="Модель ответила не таблицей — разобрать не удалось")

    items = payload.get("rows") if isinstance(payload, dict) else payload
    if not isinstance(items, list):
        return Sheet(trouble="Модель ответила не таблицей — разобрать не удалось")

    rows = tuple(row for row in (_row(item) for item in items) if row is not None)
    if not rows:
        return Sheet(trouble="Модель не нашла в спецификации ни одного предмета закупки")
    return Sheet(rows=rows)


def _row(item: object) -> Row | None:
    """Одна строка ответа. Без требования строка бессмысленна и отбрасывается."""
    if not isinstance(item, dict):
        return None
    demand = _text(item.get("demand"))
    if not demand:
        return None
    return Row(
        subject=_text(item.get("subject")),
        demand=demand,
        brief=_lines(item.get("brief")),
    )


def _text(value: object) -> str:
    return " ".join(str(value).split()) if isinstance(value, str) else ""


def _lines(value: object) -> str:
    """Выжимка построчно: пробелы внутри строки схлопываются, переводы остаются.

    Модель просят писать параметры столбиком, и склеенные в абзац они сводят
    столбец «Кратко» к тому же сплошному тексту, ради ухода от которого
    таблицу и собирают. Обратная косая с «n» приходит от модели чаще, чем
    настоящий перевод строки, — она тоже перевод.
    """
    if not isinstance(value, str):
        return ""
    rows = (" ".join(line.split()) for line in value.replace("\\n", "\n").splitlines())
    return "\n".join(line for line in rows if line)


def _unwrap(raw: str) -> str:
    """Снимает обёртку ```json, если модель её поставила."""
    text = raw.strip()
    fence = re.match(r"^```[a-zA-Z]*\s*(.*?)\s*```$", text, re.DOTALL)
    return fence.group(1).strip() if fence else text


_PROMPT = """\
Ты раскладываешь техническую спецификацию государственной закупки в таблицу.

Закупка: {title}

Текст технической спецификации:
---
{spec}
---

Верни JSON-массив. Каждый элемент — одна строка таблицы, с полями:

  "subject" — короткое складское название одним-двумя словами: проц, кулер,
              озу, ссд, экран, видео, корпус, БП, монитор, кабель, клавиатура,
              мышь, ОС. Не «Центральный процессор (CPU)», а «проц».

  "demand"  — требования заказчика к этой строке ДОСЛОВНО из спецификации.
              Перенеси весь текст, относящийся к ней, ничего не выбрасывая
              и ничего не добавляя. Не сокращай, не обобщай, не переформулируй,
              не исправляй опечатки заказчика. Это поле — то, чем потом меряют
              соответствие заявки.

  "brief"   — то же самое коротко, для снабженца, который подбирает модель.
              Только числа и ключевые слова, каждый параметр с новой строки,
              не больше трёх строк. Без пояснений, без целых предложений.
              Пример: "Ядра: 8\\nПотоки: 12\\n2.2/4.8 ГГц".

Правила, нарушать которые нельзя:

1. Составной предмет разбирается на узлы. Закупается сборка — моноблок,
   компьютер, ноутбук, сервер, — и спецификация задаёт требования к её
   начинке: заведи строку на каждый узел (экран, проц, озу, ссд, видео, порты,
   сеть, ОС, комплектация). Одна строка на весь моноблок бесполезна: снабжение
   ищет по узлам, а не по названию закупки.
2. Простой предмет остаётся одной строкой. У процессора, видеокарты или кабеля
   узлов нет, и разносить их характеристики по строкам (частота отдельно, кэш
   отдельно) нельзя.
3. Делить или не делить — решаешь ты по самой спецификации, а не по названию
   закупки. Написана она одним абзацем на весь моноблок — всё равно дели.
4. При делении требования расходятся по строкам без потерь: каждый кусок
   текста спецификации попадает ровно в одну строку, ничего не выброшено и
   ничего не повторено дважды.
5. Ничего не придумывай. Нет в спецификации блока питания — нет и строки о нём.
6. Порядок строк — как в спецификации.
7. В закупке несколько предметов и один из них разобран на узлы — пиши предмет
   как «моноблок: экран», иначе непонятно, чей это узел.
8. Ответ — только JSON-массив, без пояснений и без обёртки.
"""
