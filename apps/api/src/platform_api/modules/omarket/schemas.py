"""Формы ответов модуля OMarket.

Отдельно от доменных моделей ядра. По этим схемам генерируется клиент
фронтенда: отдавай домен напрямую — любая внутренняя правка молча ломала бы
интерфейс. И здесь же видно, что уходит наружу.

Рабочий список и разбор описаны общей формой (`platform_api.modules.schemas`)
и берутся оттуда напрямую: раздел устроен одинаково у всех модулей, а колонки
в нём всё равно приходят из книги этого проекта. Здесь остаётся то, что у
модуля своё, — готовность к работе.
"""

from __future__ import annotations

from pydantic import BaseModel


class ModuleHealth(BaseModel):
    """Готовность модуля к работе."""

    ok: bool
    core_version: str

    database: str = ""
    """С какой базой работает ядро: «PostgreSQL» или «SQLite (файл)». Забытая
    переменная окружения не ломает ничего заметного — модуль продолжает писать
    в старый файл, — поэтому видно должно быть сразу."""

    preorders: int

    session: bool
    """Жива ли сессия кабинета. Вход по ЭЦП идёт в окне браузера на машине
    сотрудника, поэтому платформа её только проверяет, а не заводит."""

    market_search: bool
    """Настроен ли поиск себестоимости на внешних рынках."""

    market_model: str
    warehouse: bool
    problems: list[str] = []


__all__ = ["ModuleHealth"]
