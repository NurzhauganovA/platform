class TakeOut(BaseModel):
    """Снимок закупки для карточки лота.

    Копией, а не ссылкой в базу площадки: выгрузка пересобирает список каждый
    час, названия и суммы у заказчика меняются, а карточка должна остаться
    той, по которой её завели.
    """

    module: str
    row_id: str
    code: str
    source_number: str = ""
    title: str
    customer: str = ""
    amount: float | None = None
    enstru_code: str = ""
    category: str = ""
    deadline: str | None = None


class SpecFile(BaseModel):
    """Документ, описывающий требования заказчика к этой строке.

    Отдельным полем, а не только разделом разбора. По одному и тому же файлу
    работают три места: вкладка разбора собирает из него таблицу, вкладка
    файлов даёт его скачать, панель сведений показывает текст. Собирать его в
    каждом из них своим способом значит завести три ответа на вопрос «а есть
    ли вообще спецификация» — и однажды получить три разных.

    Пусто — файла нет. У большинства лотов портала его действительно нет, и
    «не приложена» это ответ, а не сбой.
    """

    name: str
    """Как файл называется у заказчика. По этому имени его ищут в письме."""

    url: str = ""
    """Откуда скачать — через нас, а не с портала: портальное имя вида
    `file_1837462.docx` в папке «Загрузки» потом не найти."""

    chars: int = 0
    """Сколько знаков текста мы из него прочитали. Ноль при заполненном имени
    означает, что файл есть, а прочитать его не вышло, — и разбор моделью по
    нему не соберётся."""


class DetailOut(BaseModel):
    """Разбор одной строки: откуда взялась цифра."""

    id: str
    title: str
    subtitle: str = ""
    verdict: str = ""
    tone: str = ""
    url: str | None = None
    """Ссылка на карточку у площадки — то, ради чего разбор чаще всего и
    открывают. У тендерной закупки её нет: она пришла папкой, а не из
    кабинета."""

    take: TakeOut | None = None
    """Чем заводить карточку лота, если этот раздел это умеет.

    Снимок собирает сервер, а не браузер: в разборе строки нет ни суммы, ни
    срока в пригодном виде, а собирать их из подписей разделов значит завести
    второй источник правды о закупке.

    Пусто — раздел не заводит карточек. Кнопка, отвечающая отказом, хуже
    отсутствующей.
    """

    remark_key: str = ""
    """По какому ключу заводится обсуждение этой строки.

    Пусто — обсуждение здесь не заводится. Так у тендерного отбора: закупки
    туда приходят папкой по почте, обсуждать их не с кем, и кнопка,
    отвечающая отказом, хуже отсутствующей.

    Ключ отдельно от `id`, потому что это не одно и то же. У госзакупок `id`
    строки — номер закупки, общий у всех лотов объявления, а замечание пишется
    по конкретному лоту: на общем номере оно ушло бы заказчику про чужой
    товар.
    """

    lot: LotOut | None = None
    """Закупка целиком, если позиций в ней больше одной."""

    spec: SpecFile | None = None
    """Техническая спецификация строки, если площадка её забрала."""

    sections: list[DetailSection] = []
    hidden_sections: int = 0
    """Сколько разделов скрыто по правам. Молча урезанный разбор выглядит
    недоделанным."""


