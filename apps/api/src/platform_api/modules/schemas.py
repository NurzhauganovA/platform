"""Общая форма рабочего списка и разбора.

Раздел устроен одинаково у всех трёх модулей: таблица как в книге Excel,
цветная легенда над ней и разбор строки сбоку. Форма ответа поэтому одна.
Три её копии — по одной на модуль — разошлись бы на первой же правке: поле
добавили бы в двух местах из трёх, и третий раздел молча остался бы без него.

Что именно приходит в таблице, модуль по-прежнему решает сам: колонки берутся
из его книги, а права на них — из его `POLICY`. Общее здесь только то, во что
это упаковано.

Доменные схемы модулей (готовность, параметры прогонов) остаются у них: они
разные по существу, и сводить их значило бы описывать сессию кабинета OMarket
в ответе тендерного раздела.
"""

from __future__ import annotations

import uuid

from pydantic import BaseModel


class ColumnOut(BaseModel):
    """Колонка рабочего списка."""

    key: str
    title: str
    width: int
    format: str = "text"
    """`text`, `money`, `percent`, `quantity`, `datetime` — тот же формат, что
    у этой колонки в книге Excel."""

    align: str = "left"
    sensitive: bool = False
    """Колонка с деньгами. Приходит только тем, кому положено их видеть."""

    compact: bool = False
    """Показывать значком, а не текстом: содержимое целиком есть в разборе."""

    essential: bool = False
    """Показывать ли сразу, без прокрутки вбок."""

    role: str = ""
    """Что это за колонка по смыслу: `total`, `price`, `cost`, `profit`,
    `margin`, `quantity`. Пусто — колонка без особой роли.

    По ролям браузер считает итоги по отобранному и подбирает вид фильтра.
    Заголовки у разделов разные — «Маржа ₸», «Заработок всего, ₸»,
    «заработок», — и разбирать их на месте значит сломаться на площадке,
    которую добавят следующей."""


class CellOut(BaseModel):
    """Ячейка. Число и текст разделены: по числу сортируют, текст показывают."""

    text: str = ""
    number: float | None = None
    link: str | None = None

    tone: str = ""
    """Отметка на самой ячейке. Заливка строки занята вердиктом, а отметить
    надо значение — код ЕНС, по которому есть отечественный производитель."""


class RowLotOut(BaseModel):
    """Отметка лота в строке рабочего списка.

    Маржа здесь по всему лоту, а не по строке, и в этом весь смысл отметки:
    позиция с заработком 40% в лоте, который в минусе, — это не находка, а
    ловушка. Видно её должно быть в списке, до того как строку откроют.
    """

    key: str
    positions: int
    total: float | None = None
    margin_percent: float | None = None


class RowWorkOut(BaseModel):
    """Отметка «в работе» в строке отбора.

    Со ссылкой, а не одним словом: увидев отметку, человек хочет посмотреть,
    что там, — и без ссылки пойдёт искать лот в соседнем разделе по названию.
    """

    id: str
    code: str
    stage: str


class RowOut(BaseModel):
    """Строка таблицы вместе с подсветкой по вердикту."""

    cells: list[CellOut]

    number: int = 0
    """Место строки в списке. Показывать его нечего — им называют строку
    вслух, а он сдвигается от каждой новой закупки. Для этого есть `code`."""

    code: str = ""
    """Постоянный код строки: «TN-00042». Выдаётся один раз и остаётся при
    позиции — им её и называют."""

    deadline: str | None = None
    """Когда закрывается приём. По нему подсвечивается срочное."""

    id: str = ""
    """Чем открыть разбор этой строки. Идентификатор площадки, а не номер
    строки: номер съезжает от сортировки, и ссылка вела бы не туда."""

    focus: bool = True
    """Есть ли с этой строкой что делать. Отбор идёт в браузере, чтобы
    переключение было мгновенным."""

    tone: str = ""
    """`good`, `warning`, `info`, `critical` или пусто. Цвет дублирует вердикт
    из первой колонки, а не заменяет его: сам по себе он смысла не несёт."""

    lot: RowLotOut | None = None
    """Лот, если строку объединили с соседними позициями закупки."""

    work: RowWorkOut | None = None
    """Работа, если строку уже взяли. Такие уходят в конец списка: решение по
    ним принято, и рассматривать их заново незачем."""


class LegendItem(BaseModel):
    """Что означает цвет строки.

    Приходит с сервера, а не зашито в браузере: слова у разделов разные.
    Площадка говорит «участвовать» и «не участвовать», тендерный отбор —
    «брать» и «мимо». Один зашитый список подписал бы чужими словами тот
    раздел, который добавят следующим, и заметили бы это не сразу.
    """

    tone: str
    """`good`, `warning`, `info`, `critical`."""

    title: str
    hint: str = ""


class WorklistOut(BaseModel):
    """Рабочий список — то, ради чего человек открывает раздел."""

    sheet: str
    """Как этот же список называется в книге Excel. Подписано, чтобы человек
    знал, с каким листом сверяться."""

    columns: list[ColumnOut]
    rows: list[RowOut]

    legend: list[LegendItem] = []
    """Чем покрашены строки — словами этого раздела."""

    actions: list[str] = []
    """Что здесь можно запустить: `sync`, `analyze`, `export`. Кнопка, которую
    нечем обслужить, хуже отсутствующей: человек нажимает и получает ошибку,
    а дальше не верит и остальным кнопкам."""

    hidden_columns: int = 0
    """Сколько колонок скрыто по правам. Показывается словами: молча урезанная
    таблица выглядит как потерянные данные."""

    total: int
    """Сколько строк в работе всего — до отбора по вердикту."""

    shown: int
    """Сколько строк в отборе — с чем действительно можно работать."""

    expired: int = 0
    """Сколько с истёкшим приёмом. Из базы они не удаляются — это история, —
    но в рабочем списке их нет. Показываются по кнопке «Все строки»."""

    verdicts: dict[str, int]

    margin_total: float | None = None
    """Сколько можно заработать по всем окупающимся строкам. Не приходит тем,
    кому не видны деньги."""

    priced: int = 0
    """По скольким строкам себестоимость вообще известна. Остальные — это не
    «невыгодно», а «не с чем сравнивать»."""

    analyzed: bool = True
    """Считали ли вообще. Пустой список без этого признака выглядит как «нечего
    смотреть», хотя строки, возможно, просто ещё не оценивали."""


class DetailField(BaseModel):
    """Строка разбора: подпись и значение."""

    label: str
    text: str = ""
    number: float | None = None
    format: str = "text"
    link: str | None = None
    tone: str = ""
    """`good`, `warning`, `critical` — когда значение само по себе тревожно."""

    note: str = ""
    """Оговорка к значению. «Комиссия не известна» важнее самой цифры:
    без неё маржа завышена ровно на её величину."""


class DetailTable(BaseModel):
    """Маленькая таблица внутри раздела — предложения конкурентов и подобное."""

    columns: list[str]
    rows: list[list[str]]
    aligns: list[str] = []

    link_column: int = 0
    """В какой колонке живёт ссылка."""

    links: list[str] = []
    """Куда ведёт строка — по одной ссылке на строку, пусто если некуда."""

    picks: list[str] = []
    """Чем выбрать строку для пересчёта. Пусто — строка не выбирается."""

    chosen: list[str] = []
    """Какие строки сейчас в расчёте: по ним и посчитана себестоимость."""


class DetailSection(BaseModel):
    title: str
    fields: list[DetailField] = []
    table: DetailTable | None = None
    note: str = ""
    empty: str = ""
    """Что сказать, если раздела нет. «Конкуренты ещё не подавались» и
    «карточку не читали» — разные ответы, молчание хуже обоих."""

    collapsed: bool = False
    """Показывать свёрнутым: заголовок и счётчик, содержимое по щелчку."""


class LotPositionOut(BaseModel):
    """Позиция лота — то, чем переключаются в разборе."""

    id: str
    title: str
    quantity: float | None = None
    total: float | None = None
    cost: float | None = None
    margin_percent: float | None = None
    tone: str = ""
    current: bool = False


class LotOut(BaseModel):
    """Закупка целиком: её позиции и итог по ним.

    Приходит и до объединения. Сам факт «в этой закупке ещё две позиции» —
    уже предупреждение: заработок по одной ничего не значит, пока не видно
    остальных, которые придётся поставить вместе с ней.
    """

    key: str
    merged: bool = False
    positions: list[LotPositionOut] = []
    total: float | None = None
    cost: float | None = None
    profit: float | None = None
    margin_percent: float | None = None
    priced: int = 0
    """По скольким позициям себестоимость известна. Без этого числа итог врёт
    в лучшую сторону: непосчитанная позиция выглядит бесплатной."""


class LotMembersIn(BaseModel):
    """Позиции, которые человек выбрал в лот сам.

    Пусто — берутся соседи по папке, как предлагает разбор. Список нужен
    там, где разбор ошибся: заказчик разложил один лот по двум папкам, и
    признака этого в документах нет.
    """

    positions: list[str] = []


class PreviewBlockOut(BaseModel):
    """Кусок документа: заголовок, абзац или таблица."""

    kind: str
    text: str = ""
    rows: list[list[str]] = []


class PreviewSheetOut(BaseModel):
    """Лист книги."""

    title: str
    rows: list[list[str]] = []
    truncated: bool = False


class PreviewOut(BaseModel):
    """Чем показать документ закупки, не выходя из платформы.

    Отдаётся разобранное, а не размётка: собери сервер HTML — и содержимое
    чужого документа стало бы кодом на нашей странице.
    """

    kind: str
    """`pdf`, `image`, `document`, `sheet` или `none`."""

    name: str = ""
    size_bytes: int = 0
    blocks: list[PreviewBlockOut] = []
    sheets: list[PreviewSheetOut] = []
    truncated: bool = False
    note: str = ""
    """Почему показать нельзя. Молчание читается как поломка платформы."""


class DetailOut(BaseModel):
    """Разбор одной строки: откуда взялась цифра."""

    id: str
    title: str
    subtitle: str = ""
    verdict: str = ""
    tone: str = ""
    url: str | None = None
    """Ссылка на карточку у площадки — то, ради чего разбор чаще всего и
    открывают. У тендерной закупки её нет: она пришла папкой, а не из
    кабинета."""

    lot: LotOut | None = None
    """Закупка целиком, если позиций в ней больше одной."""

    sections: list[DetailSection] = []
    hidden_sections: int = 0
    """Сколько разделов скрыто по правам. Молча урезанный разбор выглядит
    недоделанным."""


class StartedJobOut(BaseModel):
    """Задача принята в работу."""

    job_id: uuid.UUID


