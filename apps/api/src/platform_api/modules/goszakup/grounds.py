"""Правовая основа замечаний к технической спецификации.

Замечание держится не на возмущении, а на ссылке: заказчик обязан ответить по
существу на указание конкретного пункта Правил, а на «нам неудобно» отвечать
не обязан. Поэтому основания перечислены здесь явным списком, а не
пересказываются моделью своими словами.

Почему списком, а не в подсказке модели. Модель охотно выдумывает номер
пункта: «п. 415 Правил» выглядит так же убедительно, как настоящий, и ошибку
видно только заказчику — который на этом основании замечание и отклонит.
Ссылки берутся отсюда подстановкой; модель решает, какое основание подходит,
и не сочиняет само основание.

Состав списка — из замечаний, которые заказчики принимали. Каждое основание
описано тем, что нужно проверить в спецификации, и тем, чем это заканчивается
по закону. Прецеденты (отменённые закупки) в список не входят: они устаревают
за месяцы, их место в базе, а не в коде.

Отсюда же берётся порог тысячекратного МРП. Он меняется раз в год законом о
бюджете, и посчитанный моделью «на память» разошёлся бы с настоящим ровно
тогда, когда на нём держится всё замечание.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from decimal import Decimal


@dataclass(frozen=True, slots=True)
class Ground:
    """Одно основание для замечания."""

    key: str
    """Короткое имя. По нему основание выбирает модель и по нему же его
    узнаёт человек в списке."""

    title: str
    """Как называется нарушение на языке сотрудника."""

    law: str
    """Ссылка на норму — то, ради чего всё и затевается."""

    look_for: str
    """Что искать в технической спецификации. Идёт в подсказку модели."""

    claim: str
    """Чем это заканчивается по закону — основа абзаца замечания."""

    marks: tuple[str, ...]
    """Слова, по которым основание узнаётся в готовом тексте.

    Задаются явно, а не выводятся из номера нормы. Номера у оснований
    повторяются: «пункт 3 статьи 6» стоит и у программного обеспечения, и у
    сборного лота, а «412» встречается в коде ЕНС ТРУ. Поиск по числу
    отмечал применёнными все шесть оснований разом, и список у менеджера
    переставал что-либо значить.
    """


MRP: dict[int, Decimal] = {
    2025: Decimal("3932"),
    2026: Decimal("4325"),
}
"""Месячный расчётный показатель по годам.

Задаётся законом о республиканском бюджете и меняется с 1 января. На нём
держится порог, ниже которого указывать бренд разрешено, — то есть половина
замечаний. Год, которого здесь нет, лучше признать неизвестным, чем взять
соседний: замечание с чужим порогом заказчик отклонит по существу.
"""

BRAND_LIMIT_MRP = 1000
"""Во сколько раз сумма закупки должна превысить МРП, чтобы запрет на
указание бренда действовал безусловно."""


def brand_threshold(on: date) -> Decimal | None:
    """Порог, выше которого бренд указывать нельзя ни при каких условиях.

    Возвращает `None` за год, МРП которого не задан. Пустой порог означает
    «этот довод не приводим»; выдуманный означает отклонённое замечание.
    """
    mrp = MRP.get(on.year)
    if mrp is None:
        return None
    return mrp * BRAND_LIMIT_MRP


