"""Работа: сквозной путь лота через отделы.

Модуль платформы, а не проекта. У соседей за модулем стоит подключённое ядро
со своей базой и своим CLI; здесь ядра нет — есть то, что делает компания с
лотом после того, как он найден: обсуждение, разбор, согласование, подача,
договор.

Оформлен модулем ради меню. Пункт, вписанный в оболочку руками, означал бы,
что контракт модулей сломан, и следующий сквозной раздел пришлось бы вписывать
туда же. Ядра у модуля нет, поэтому нет и проверки готовности: проверять
нечего, таблицы свои и живут в базе платформы.

Стоит первым: с этого экрана начинается день. Площадки обновляются сами и
показывают, что появилось; здесь то, что уже взято и чего от нас ждут.
"""

from platform_api.auth.dependencies import CRM, names
from platform_api.modules import ModuleSpec, NavItem
from platform_api.modules.cards_router import router

module = ModuleSpec(
    slug="work",
    title="Работа",
    description="Лоты в работе: от объявления до оплаты",
    router=router,
    nav=(
        # Порядок групп — порядок дня. Сначала свой стол: с него начинают,
        # там то, чего ждут от тебя. Потом лоты целиком и то, что делают
        # перед подачей.
        NavItem(
            title="Лоты в работе",
            path="/work/lots",
            icon="table",
            group="Мой стол",
            # Первым пунктом и первым в разделе: с него начинают день. Очереди
            # отделов ниже отвечают на «что от меня ждут», а этот экран — на
            # «что вообще происходит», и утром спрашивают именно его.
            #
            # Смотрят все отделы: у каждого в карточке своё. Закупщик видит
            # задачи снабжения, юрист — свои; сумма закупки при этом
            # опубликована на портале и секретом не является.
            roles=names(*CRM),
        ),
        NavItem(
            title="Разбор",
            path="/work/analysis",
            icon="list",
            group="Мой стол",
            roles=("admin", "manager", "analyst"),
        ),
        NavItem(
            title="Снабжение",
            path="/work/supply",
            icon="list",
            group="Мой стол",
            roles=("admin", "manager", "buyer"),
        ),
        NavItem(
            title="Юристы",
            path="/work/legal",
            icon="list",
            group="Мой стол",
            roles=("admin", "manager", "lawyer"),
        ),
        NavItem(
            title="Подача",
            path="/work/submit",
            icon="calendar",
            group="Работа",
            # Подают менеджеры. Остальным этот календарь показывает чужую
            # работу по минутам и ничего им не даёт.
            roles=("admin", "manager"),
        ),
        NavItem(
            title="Согласование",
            path="/work/approval",
            icon="check",
            group="Работа",
            # Все пятеро подписывающих плюс те, кто следит, собрано ли.
            # Наблюдателя нет: карточка это стол, а не отчёт.
            roles=names(*CRM),
        ),
    ),
)

__all__ = ["module"]
