"""Работа: сквозной путь лота через отделы.

Модуль платформы, а не проекта. У соседей за модулем стоит подключённое ядро
со своей базой и своим CLI; здесь ядра нет — есть то, что делает компания с
лотом после того, как он найден: обсуждение, разбор, согласование, подача,
договор.

Оформлен модулем ради меню. Пункт, вписанный в оболочку руками, означал бы,
что контракт модулей сломан, и следующий сквозной раздел пришлось бы вписывать
туда же. Ядра у модуля нет, поэтому нет и проверки готовности: проверять
нечего, таблицы свои и живут в базе платформы.

Стоит первым: с этого экрана начинается день. Площадки обновляются сами и
показывают, что появилось; здесь то, что уже взято и чего от нас ждут.
"""

from platform_api.auth.dependencies import CRM, names
from platform_api.modules import ModuleSpec, NavItem
from platform_api.modules.cards_router import router
from platform_api.modules.work.jobs import jobs

module = ModuleSpec(
    slug="work",
    title="Работа",
    description="Лоты в работе: от объявления до оплаты",
    router=router,
    jobs=jobs,
    nav=(
        # Порядок групп — порядок дня. Сначала свой стол: с него начинают,
        # там то, чего ждут от тебя. Потом лоты целиком и то, что делают
        # перед подачей.
        NavItem(
            title="Лоты в работе",
            path="/work/lots",
            permission="page.lots",
            icon="table",
            group="Мой стол",
            # Первым пунктом и первым в разделе: с него начинают день. Очереди
            # отделов ниже отвечают на «что от меня ждут», а этот экран — на
            # «что вообще происходит», и утром спрашивают именно его.
            #
            # Смотрят все отделы: у каждого в карточке своё. Закупщик видит
            # задачи снабжения, юрист — свои; сумма закупки при этом
            # опубликована на портале и секретом не является.
            roles=names(*CRM),
        ),
        NavItem(
            title="Задачи",
            path="/work/tasks",
            permission="page.tasks",
            icon="list",
            group="Мой стол",
            # Личный раздел, а не очередь отдела: что поручили мне и что
            # поручил я. Поручение вне лота — «собрать доверенности», «оформить
            # пропуск на склад» — до сих пор жило в мессенджере, то есть нигде:
            # срока у него не было, и спросить о нём было не с кого.
            #
            # Роли перечислены все, кто вообще заходит в платформу: поручение
            # дают человеку, а не должности, и раздел без пункта означал бы
            # задачу, о которой исполнитель узнаёт только из уведомления.
            roles=(*names(*CRM), "viewer"),
        ),
        NavItem(
            title="Обсуждение",
            path="/work/discussion",
            permission="page.desk_discussion",
            icon="list",
            group="Мой стол",
            # Тот же стол, что у разбора и снабжения. Задачи отделу
            # «Обсуждение» заводились с самого начала — в карточке лота есть
            # такой блок, — а увидеть их было негде: очередь отдела просто не
            # показывалась, и заведённая задача уходила в никуда.
            roles=("admin", "manager", "lawyer", "analyst"),
        ),
        NavItem(
            title="Разбор",
            path="/work/analysis",
            permission="page.desk_analysis",
            icon="list",
            group="Мой стол",
            roles=("admin", "manager", "analyst"),
        ),
        NavItem(
            title="Снабжение",
            path="/work/supply",
            permission="page.desk_supply",
            icon="list",
            group="Мой стол",
            roles=("admin", "manager", "buyer"),
        ),
        NavItem(
            title="Юристы",
            path="/work/legal",
            permission="page.desk_legal",
            icon="list",
            group="Мой стол",
            roles=("admin", "manager", "lawyer"),
        ),
        NavItem(
            title="Подача",
            path="/work/submit",
            permission="page.submit",
            icon="calendar",
            group="Работа",
            # Подают менеджеры. Остальным этот календарь показывает чужую
            # работу по минутам и ничего им не даёт.
            roles=("admin", "manager"),
        ),
        NavItem(
            title="Журнал действий",
            path="/work/audit",
            permission="page.audit",
            icon="list",
            group="Работа",
            # Только администратору. Журнал отвечает на вопрос «кто это
            # сделал», и человек, о котором его спрашивают, не должен видеть,
            # что именно о нём записано: иначе первым делом он посмотрит,
            # попал ли туда. Права проверяются на эндпоинте — пункт меню это
            # удобство, а не защита.
            roles=("admin",),
        ),
        NavItem(
            title="Сотрудники",
            path="/work/people",
            permission="page.people",
            icon="settings",
            group="Работа",
            # Только администратору: за экраном почты всех сотрудников, их роли
            # и право выдать себе любое из прав. Вопрос «кто может видеть
            # себестоимость» задаёт не тот, кому её не показывают.
            roles=("admin",),
        ),
        NavItem(
            title="Уведомления",
            path="/work/notifications",
            permission="page.notify",
            icon="bell",
            group="Работа",
            # Только администратору: за экраном почты всех сотрудников и то,
            # кто из них что себе отключил. Вопрос «почему Ивану не приходит»
            # задаёт не Иван.
            roles=("admin",),
        ),
        NavItem(
            title="Согласование",
            path="/work/approval",
            permission="page.approval",
            icon="check",
            group="Работа",
            # Все пятеро подписывающих плюс те, кто следит, собрано ли.
            # Наблюдателя нет: карточка это стол, а не отчёт.
            roles=names(*CRM),
        ),
    ),
)

__all__ = ["module"]
