"""Пересборка по состоянию базы, а не на каждый запрос.

Рабочие списки площадок собираются прогоном ядра: оно поднимает закупы,
находки на рынке и склад и пересчитывает вердикты. Обращений наружу при этом
нет и денег это не стоит, но процессора стоит секунд, а при тысяче с лишним
строк — десятков секунд.

Пока раздел открывает один человек, это терпимо. Тридцать человек в начале дня
превращают это в стену: работа процессорная, процесс API один, и GIL
выстраивает всех в очередь — соседние разделы ждут вместе с ними. Замер по
skstore: один запрос 3,9 с, четыре одновременно — 26 с.

Кэш сбрасывается не по времени, а по содержимому базы. Срок жизни был бы хуже
обоих вариантов: короткий не спасает, длинный показывает вчерашние числа после
того, как прогон отработал. Отпечаток считается запросом к базе ядра — он
дешёвый и, главное, видит правки, сделанные не этим процессом: прогоны идут в
отдельном исполнителе, и его записи иначе остались бы незамеченными.

Тендерный модуль пришёл к тому же раньше и держит свою копию этого механизма
внутри `tender/worklist.py` — вместе со сборкой, файлами закупок и находками,
которые кэшируются одним куском. Растаскивать её сюда значит трогать
работающий разбор ради красоты; здесь общий помощник для площадок.
"""

from __future__ import annotations

import threading
from collections.abc import Callable

from platform_api.logging import get_logger

logger = get_logger(__name__)


class ByStamp[T]:
    """Значение, которое пересобирается, когда меняется отпечаток базы.

    Отпечаток не посчитался — собираем заново и не запоминаем. Показать старое
    в этом случае нельзя: неизвестно, устарело оно или нет, а рабочий список с
    ценами вчерашнего дня выглядит точно так же, как сегодняшний.
    """

    def __init__(self, name: str, stamp: Callable[[], str], build: Callable[[], T]) -> None:
        self._name = name
        self._stamp = stamp
        self._build = build
        # Собирает кто-то один. Без замка утро выглядит так: прогон закончился,
        # отдел открывает раздел, и десять запросов одновременно не находят
        # кэша — каждый честно пересобирает те же строки. Замок делает из
        # десяти пересборок одну: первый строит, остальные забирают готовое.
        self._lock = threading.Lock()
        self._at: str | None = None
        self._value: T | None = None

    def get(self) -> T:
        stamp = self._read_stamp()
        ready = self._hit(stamp)
        if ready is not None:
            return ready

        with self._lock:
            # Пока ждали замок, значение мог собрать тот, кто зашёл первым.
            ready = self._hit(stamp)
            if ready is not None:
                return ready

            value = self._build()
            if stamp is not None:
                self._at, self._value = stamp, value
            return value

    def forget(self) -> None:
        """Забыть собранное. Нужно тестам и перенастройке ядра на другую базу."""
        with self._lock:
            self._at, self._value = None, None

    def _hit(self, stamp: str | None) -> T | None:
        if stamp is None or self._at != stamp:
            return None
        return self._value

    def _read_stamp(self) -> str | None:
        try:
            return self._stamp()
        except Exception as exc:  # pragma: no cover — база ядра недоступна
            # Не ошибка запроса: без отпечатка список всё равно соберётся, просто
            # без экономии. Пятисотый ответ здесь означал бы пустой экран там,
            # где данные есть.
            logger.warning("Отпечаток базы не посчитался", core=self._name, error=str(exc))
            return None


__all__ = ["ByStamp"]
