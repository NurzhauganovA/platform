"""Что такое фоновая задача с точки зрения модуля.

Модуль объявляет задачи, а не запускает их сам. Каркас берёт на себя всё, что
одинаково для любого проекта: учёт состояния, прогресс, ошибки, стоимость,
отмену. Модулю остаётся предметная работа — разобрать документы, поискать на
рынке, собрать КП.

Обработчик синхронный намеренно. Ядра проектов синхронные: они читают PDF,
гоняют OCR и ходят в модель блокирующими вызовами. Просить их притвориться
асинхронными значит развести два способа делать одно и то же и однажды позвать
блокирующий код из цикла событий — там он остановит весь сервер.
"""

from __future__ import annotations

import uuid
from collections.abc import Callable
from dataclasses import dataclass
from typing import Any, Protocol

from sqlalchemy.orm import Session as DbSession

from platform_api.storage import FileStorage


class CancelledError(Exception):
    """Задачу отменили — работу нужно прекратить.

    Отмена не ошибка: человек передумал, и разбор, за который иначе пришлось
    бы заплатить до конца, останавливается.
    """


class JobContext(Protocol):
    """Что обработчик получает от каркаса."""

    job_id: uuid.UUID
    organization_id: uuid.UUID
    user_id: uuid.UUID | None

    db: DbSession
    storage: FileStorage
    workspace: Any
    """Каталоги закупок. Тип не уточняется намеренно: устройство рабочего
    каталога — дело модуля, а каркас только передаёт его обработчику."""

    def advance(self, done: int, *, total: int | None = None, note: str = "") -> None:
        """Двигает прогресс и проверяет, не отменили ли задачу.

        Проверка именно здесь, а не отдельным вызовом: обработчик и так
        сообщает о каждом шаге, и лишний повод забыть про отмену ни к чему.
        Бросает `Cancelled`, если задачу погасили.
        """
        ...


@dataclass(frozen=True, slots=True)
class JobSpec:
    """Объявление одной задачи модуля."""

    kind: str
    """Имя задачи внутри модуля: `analyze`, `sourcing`, `offer`."""

    handler: Callable[..., dict[str, Any]]
    """Что выполнять. Первым аргументом получает контекст, остальное —
    параметры задачи как есть."""

    title: str = ""
    """Как задача называется для человека."""

    every_hours: int = 0
    """Как часто запускать без человека. 0 — только по кнопке.

    Объявляет модуль, а не исполнитель: расписание — часть того, как раздел
    живёт, и вынесенное в каркас оно разъедется с задачами при первой же
    правке. Проверено на своей шкуре: пока расписания не было вовсе, выгрузку
    запускали руками, и два раздела из четырёх простояли пустыми три недели —
    все строки в них успели протухнуть.

    Ставится только бесплатным задачам. Платный шаг, запускающий себя сам,
    однажды потратит бюджет за ночь, и объяснить это будет нечем.
    """

    at_minute: int = 0
    """На какой минуте часа. Разнесены по модулям намеренно: три выгрузки,
    стартующие разом, дерутся за единственный процессор и растягивают друг
    друга втрое."""

    on_lost: Callable[[DbSession, Any], None] | None = None
    """Что отпустить, если прогон оборвался вместе с исполнителем.

    Задача пометится прерванной сама, но своё состояние модуль держит у себя, и
    каркас про него не знает. Обсуждение помечается «модель пишет» на время
    прогона; исполнитель убит выкладкой — пометка остаётся, и человек смотрит
    на колесо до конца дня, потому что писать заново, пока «идёт», нельзя.

    Объявляет модуль, а не исполнитель: знание о том, что именно заперто,
    живёт рядом с задачей, которая это заперла. Получает сессию платформы и
    саму запись задачи — по её параметрам и находит, что отпускать."""

    def __post_init__(self) -> None:
        if not self.kind:
            raise ValueError("У задачи должно быть имя")
        if self.every_hours and not 0 <= self.at_minute < 60:
            raise ValueError("Минута запуска — от 0 до 59")
        if self.every_hours and not 0 < self.every_hours <= 24:
            raise ValueError("Частота запуска — от часа до суток")


__all__ = ["CancelledError", "JobContext", "JobSpec"]
