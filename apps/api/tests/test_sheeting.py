"""Подсказка модели для таблицы спецификации и разбор её ответа.

Без сети и без денег: то, что можно проверить на месте, здесь и проверяется.
Сам поход к модели подменяется в тестах службы.
"""

from __future__ import annotations

from platform_api.modules import sheeting


def test_fail_podskazka_zapreshchayet_pereskaz() -> None:
    """Требование заказчика переносится дословно, и модели это сказано прямо.

    Это поле — то, чем меряют соответствие заявки. Пересказ здесь означает
    заявку, поданную по придуманным требованиям: «не менее 8 ядер» вместо «не
    менее 16 потоков» видно только заказчику, и видит он это при отклонении.
    """
    подсказка = sheeting.prompt(title="Компьютер в комплекте", spec="Процессор: не менее 8 ядер")

    assert "ДОСЛОВНО" in подсказка
    assert "Не сокращай" in подсказка
    assert "Ничего не придумывай" in подсказка
    assert "Компьютер в комплекте" in подсказка
    assert "Процессор: не менее 8 ядер" in подсказка


def test_fail_dlinnaya_specifikaciya_obrezayetsya() -> None:
    """Многотомник не должен съедать окно модели целиком.

    Съеденное окно означает ответ обрывком, а обрыв приходится на конец
    таблицы — туда, где кабели и мелочь, которую в заявке как раз и забывают.
    """
    # Знак, которого нет в самой подсказке: иначе счёт поймает её слова.
    подсказка = sheeting.prompt(title="Лот", spec="§" * (sheeting.MAX_SPEC + 5_000))

    assert подсказка.count("§") == sheeting.MAX_SPEC


def test_fail_otvet_v_obertke_razbirayetsya() -> None:
    """Модель любит обернуть JSON в ```json — это не повод терять таблицу."""
    ответ = sheeting.shape(
        '```json\n[{"subject": "проц", "demand": "Ядер не менее 8", "brief": "8 ядер"}]\n```'
    )

    assert ответ.trouble == ""
    assert len(ответ.rows) == 1
    assert ответ.rows[0].subject == "проц"


def test_fail_stroka_bez_trebovaniya_otbrasyvayetsya() -> None:
    """Без требования строка бессмысленна: сравнивать заявку не с чем."""
    ответ = sheeting.shape('[{"subject": "проц", "demand": ""}, {"demand": "Ядер 8"}]')

    assert len(ответ.rows) == 1
    assert ответ.rows[0].demand == "Ядер 8"


def test_fail_ne_json_ne_lomayet_platformu() -> None:
    """Модель ответила прозой — таблица не собралась, и сказано почему.

    Не исключение: разобрать спецификацию руками человек может и сам, а
    красный крест без объяснения отправляет его искать поломку у нас.
    """
    ответ = sheeting.shape("Извините, я не могу выполнить этот запрос")

    assert ответ.rows == ()
    assert "разобрать не удалось" in ответ.trouble


def test_fail_pustoy_otvet_nazvan_pustym() -> None:
    """Пустой ответ и непонятый ответ — разные причины и разные действия."""
    assert "пустой" in sheeting.shape("   ").trouble


def test_fail_sostavnoy_predmet_delitsya_na_uzly() -> None:
    """Моноблок раскладывается по узлам, а простой предмет остаётся строкой.

    Одна строка на весь моноблок бесполезна: снабжение ищет экран, процессор и
    накопитель порознь, у каждого свой поставщик и своя цена. Обратное тоже
    важно — разнести частоту и кэш процессора по строкам значит выдумать
    предметы, которых в закупке нет.
    """
    подсказка = sheeting.prompt(title="Приобретение моноблока", spec="Диагональ 23.8")

    assert "моноблок" in подсказка
    assert "узел" in подсказка
    assert "Простой предмет остаётся одной строкой" in подсказка


def test_fail_vyzhimka_khranitsya_stolbikom() -> None:
    """Переводы строк в «Кратко» переживают разбор ответа.

    Столбец узкий, и склеенная в абзац выжимка возвращает тот самый сплошной
    текст, ради ухода от которого таблицу и собирают. Модель шлёт перевод
    строки то настоящим, то обратной косой с «n» — оба означают одно.
    """
    ответ = sheeting.shape(
        '[{"subject": "проц", "demand": "Ядер 8", "brief": "Ядра:  8\\nПотоки: 12\\n\\n"}]'
    )

    assert ответ.rows[0].brief == "Ядра: 8\nПотоки: 12"


def test_fail_kazakhskaya_polovina_ne_uhodit_modeli() -> None:
    """Спецификации портала двуязычные: тот же текст сперва по-казахски.

    Половина знаков — перевод того же самого. Модели она не нужна, а стоит
    дорого: «Требование заказчика» переносится дословно, ответ растёт вместе с
    исходником и упирается в потолок объёма — на сервере из четырнадцати
    страниц он обрывался посреди таблицы.
    """
    текст = (
        "Процессор ядроларының саны: кемінде 10.\n"
        "Количество ядер процессора: не менее 10.\n"
        "Жедел жадының көлемі: кемінде 32 ГБ.\n"
        "Объём оперативной памяти: не менее 32 ГБ."
    )

    осталось = sheeting.russian(текст)

    assert "Количество ядер процессора: не менее 10." in осталось
    assert "Объём оперативной памяти: не менее 32 ГБ." in осталось
    assert "кемінде" not in осталось


def test_fail_kazakhskiy_bez_russkogo_ostayotsya_kak_yest() -> None:
    """Русского перевода нет — разбираем казахский.

    Спецификация на чужом языке хуже, чем на своём, но лучше, чем никакая:
    выбросив её целиком, мы оставили бы человека с пустой таблицей и без
    объяснения, почему она пуста.
    """
    текст = "Процессор ядроларының саны: кемінде 10. Жедел жадының көлемі: кемінде 32 ГБ."

    assert sheeting.russian(текст) == текст


def test_fail_russkoye_predlozheniye_s_kazakhskim_nazvaniyem_ostayotsya() -> None:
    """«ТОО «Қазақмыс»» в русской фразе — это по-прежнему русская фраза.

    Выброшенная по одной букве, она унесла бы с собой требование заказчика — а
    им меряют соответствие заявки.
    """
    текст = "Поставщик — ТОО «Қазақмыс», срок поставки не более 30 дней."

    assert sheeting.russian(текст) == текст


def test_fail_obyom_otveta_schitayetsya_ot_specifikacii() -> None:
    """Постоянный потолок рвал ответ ровно на длинных спецификациях — тех,
    ради которых разбор и заводили."""
    короткая = sheeting.budget("Процессор: не менее 8 ядер", ceiling=32_000)
    длинная = sheeting.budget("Процессор: не менее 8 ядер. " * 1_000, ceiling=32_000)

    assert короткая < длинная
    assert длинная <= 32_000
    # Даже на пустой закупке просим столько, чтобы хватило на несколько строк.
    assert sheeting.budget("", ceiling=32_000) >= 4_096


def test_fail_oborvannyy_otvet_sohranyayet_razobrannoye() -> None:
    """Обрыв по объёму — не повод потерять разобранное.

    Модель успела разложить десять предметов из двенадцати; выбросить их
    значит заставить человека раскладывать всё заново. Но и промолчать нельзя:
    таблица без хвоста — это заявка без блока питания.
    """
    оборванный = (
        '[{"subject": "проц", "demand": "Ядер не менее 8", "brief": "8 ядер"},'
        ' {"subject": "озу", "demand": "Не менее 32 ГБ", "brief": "32 ГБ"},'
        ' {"subject": "ссд", "demand": "Не мен'
    )

    ответ = sheeting.shape(оборванный, cut=True)

    assert len(ответ.rows) == 2
    assert ответ.rows[1].subject == "озу"
    assert "не дописала" in ответ.trouble


def test_fail_oborvannyy_bez_edinoy_stroki_nazyvayet_prichinu() -> None:
    """Ответ оборвался на первой же строке — причина не «ответила не таблицей»,
    а «не поместился объём». Чинят их по-разному."""
    ответ = sheeting.shape('[{"subject": "проц", "demand": "Яд', cut=True)

    assert ответ.rows == ()
    assert "не поместился" in ответ.trouble


def test_fail_json_sredi_poyasneniy_nahoditsya() -> None:
    """Модель предваряет массив строкой «Вот таблица» через раз.

    Просьба «только JSON» выполняется через раз, и терять из-за неё разбор —
    то же самое, что не разбирать вовсе.
    """
    ответ = sheeting.shape(
        'Вот таблица:\n[{"subject": "проц", "demand": "Ядер не менее 8"}]\nГотово.'
    )

    assert ответ.trouble == ""
    assert len(ответ.rows) == 1


def test_fail_podskazka_govorit_pro_dva_yazyka() -> None:
    """Отбор половины — не гарантия: перемешанные в одной строке языки
    остаются, и модель должна знать, какой из них переносить."""
    подсказка = sheeting.prompt(title="Сервер", spec="Процессор: не менее 8 ядер")

    assert "по-русски" in подсказка
    assert "не переводи" in подсказка
